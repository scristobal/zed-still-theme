// Zed's default semantic token rules already style class, struct, enum,
// interface, type, and type parameter declarations with the theme's
// type.*.definition keys. These rules color the remaining declarations and keep
// parameter references plain. Zed applies the first rule that matches.
export function createRules() {
  const rules = [];
  const declare = (tokenType, modifiers, style) => {
    for (const modifier of ['declaration', 'definition']) {
      rules.push({ token_type: tokenType, token_modifiers: [...modifiers, modifier], style: [style] });
    }
  };
  // Neovim Still treats a binding to a closure as a function definition.
  declare('variable', ['callable'], 'function.definition');
  for (const type of ['function', 'method', 'macro']) declare(type, [], 'function.definition');
  // rust-analyzer reports type aliases and unions as their own token types.
  for (const type of ['namespace', 'typeAlias', 'union']) declare(type, [], 'type.definition');
  for (const type of ['variable', 'parameter', 'property', 'enumMember']) declare(type, [], 'variable.definition');
  // Zed's default gives every parameter the declaration color.
  rules.push({ token_type: 'parameter', style: ['variable'] });
  return rules;
}

const field = ([key, value]) => `${JSON.stringify(key)}: ${JSON.stringify(value).replaceAll('","', '", "')}`;

export function formatSettings(rules) {
  return [
    '// Still for Zed: semantic token settings.',
    '// Generated by `npm run build`. Merge into settings.json, placing these rules',
    '// before any existing semantic_token_rules.',
    '{',
    '\t"semantic_tokens": "combined",',
    '\t"global_lsp_settings": {',
    '\t\t"semantic_token_rules": [',
    ...rules.map((rule, i) => `\t\t\t{ ${Object.entries(rule).map(field).join(', ')} }${i < rules.length - 1 ? ',' : ''}`),
    '\t\t]',
    '\t}',
    '}',
    '',
  ].join('\n');
}
